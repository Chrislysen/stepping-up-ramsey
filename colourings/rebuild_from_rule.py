"""Rebuild a colouring from its short rule and compare it with the stored one.

    python rebuild_from_rule.py R553_98_points.json

The rule (the "rule" entry of the JSON file): the points 0..m-1 are the integers mod m; any further points are left
in place by every map. The maps are x -> g * x + b (mod m), for b in 0..m-1 and g in the group of multipliers
generated by "multipliers". Colour 0 is the union of the orbits of the listed subsets under these maps; every other
subset has colour 1. Standard library only.
"""
import hashlib
import itertools
import json
import sys

w = json.load(open(sys.argv[1], encoding="utf-8"))
n, t, rule = w["n"], w["uniformity"], w["rule"]
m = rule["modulus"]
group, todo = {1}, [1]
while todo:
    x = todo.pop()
    for a in rule["multipliers"]:
        y = x * a % m
        if y not in group:
            group.add(y)
            todo.append(y)
colour0 = set()
for rep in rule["colour0_orbit_representatives"]:
    for g in group:
        for b in range(m):
            colour0.add(tuple(sorted((g * x + b) % m if x < m else x for x in rep)))
rebuilt = "".join("0" if s in colour0 else "1" for s in itertools.combinations(range(n), t))
same = rebuilt == w["colouring"] and hashlib.sha256(rebuilt.encode()).hexdigest() == w["sha256_of_colouring"]
print(f"{sys.argv[1]}: {len(group) * m} maps, {len(rule['colour0_orbit_representatives'])} orbits in colour 0, "
      f"{len(colour0)} subsets in colour 0 -> " + ("THE SAME COLOURING" if same else "DIFFERENT"))
sys.exit(0 if same else 1)
